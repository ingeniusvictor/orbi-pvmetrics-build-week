const clampQuality = (value: number) => Math.max(0, Math.min(100, value));

const calculateSummary = (
  signals: PVMetricsExpectedSignal[],
): PVMetricsSignalMappingDataset['summary'] => {
  const mappedSignals = signals.filter((signal) =>
    ['mapped-demo', 'mapped-readonly'].includes(signal.mappingStatus),
  ).length;

  const pendingSignals = signals.filter((signal) =>
    ['pending-mapping', 'requires-client-data', 'not-authorized'].includes(
      signal.mappingStatus,
    ),
  ).length;

  const validSignals = signals.filter(
    (signal) => signal.validationStatus === 'valid',
  ).length;

  const warningSignals = signals.filter(
    (signal) => signal.validationStatus === 'warning',
  ).length;

  const missingSignals = signals.filter(
    (signal) => signal.validationStatus === 'missing',
  ).length;

  const averageQualityPct = signals.length
    ? Math.round(
        signals.reduce((sum, signal) => sum + clampQuality(signal.qualityPct), 0) /
          signals.length,
      )
    : 0;

  const criticalSignals = signals.filter(
    (signal) => signal.criticality === 'critical',
  ).length;

  return {
    totalSignals: signals.length,
    mappedSignals,
    pendingSignals,
    validSignals,
    warningSignals,
    missingSignals,
    averageQualityPct,
    criticalSignals,
  };
};

